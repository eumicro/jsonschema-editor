export function appUiFor(locale: AppLocale) {
  return appUi[locale as keyof typeof appUi] ?? appUi.de;
}

export function fallbackLocaleFor(locale: AppLocale): AppLocale {
  return locale === "en" ? "de" : "en";
}

export function categoryLabelFor(locale: AppLocale, category: string): string {
  const labelsMap = appUiFor(locale).categoryLabels as Record<string, string>;
  return labelsMap[category] ?? category;
}
